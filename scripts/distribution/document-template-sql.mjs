/**
 * Writes the three SQL files that bring the document templates of hall.document_template to the current defaults:
 * - the schema manifest gives a new installation the default template of every generated document;
 * - migration 005 inserts the attendance sheet and proxy form families when absent;
 * - the replacement script, run by hand after backup, replaces the body and stylesheet of the
 *   signed templates still identical to their default of the previous release, keeping their
 *   identifiers, and lists the customized ones left unchanged.
 * `--check` fails when a file differs from the current defaults instead of writing it.
 */
import { execFileSync } from "node:child_process";
import { existsSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
const migrationsDirectory = join(root, "packages/postgres/sql/migrations");
export const previousRelease = "v1.0.3";
export const insertedTypes = ["attendance-sheet", "proxy-form"];
export const replacedTypes = ["minutes", "meeting-notice", "council-decision", "deliberation-list", ...insertedTypes];
export const migrationPath = join(migrationsDirectory, "005-attendance-sheet-and-proxy-form-templates.sql");
export const replacementPath = join(migrationsDirectory, "replace-default-templates-1.0.4.sql");
export const installationPath = join(root, "packages/postgres/sql/administration/030-default-document-templates.sql");

const literal = (value) => (value === null ? "NULL" : `'${value.replaceAll("'", "''")}'`);

async function domainTemplates() {
  return import(pathToFileURL(join(root, "packages/domain/dist/generatedDocumentTemplates.js")).href);
}

async function currentDefaults() {
  return (await domainTemplates()).defaultDocumentTemplates;
}

/** Defaults of the previous release, evaluated from its sources. */
export async function previousDefaults() {
  const directory = mkdtempSync(join(tmpdir(), "hall-previous-templates-"));
  try {
    for (const name of ["generatedDocumentTemplates.ts", "jinjaDocumentTemplates.ts"])
      writeFileSync(
        join(directory, name),
        execFileSync("git", ["show", `${previousRelease}:packages/domain/src/${name}`], { cwd: root }),
      );
    writeFileSync(join(directory, "model.ts"), "export type ContentTemplate = Record<string, unknown>;\n");
    const output = execFileSync(
      process.execPath,
      [
        "--import",
        "tsx",
        "--input-type=module",
        "-e",
        `const m = await import(${JSON.stringify(pathToFileURL(join(directory, "generatedDocumentTemplates.ts")).href)}); process.stdout.write(JSON.stringify(m.defaultDocumentTemplates));`,
      ],
      { cwd: root, maxBuffer: 16 * 1024 * 1024 },
    );
    return JSON.parse(output.toString("utf8"));
  } finally {
    rmSync(directory, { recursive: true, force: true });
  }
}

function insertSql(template, indent) {
  return `${indent}INSERT INTO hall.document_template (kind, document_type, name, body_markdown, subject, stylesheet, header_html, footer_html)
${indent}SELECT ${literal(template.kind)}, ${literal(template.documentType)}, ${literal(template.name)},
${indent}  ${literal(template.bodyMarkdown)}, ${literal(template.subject)}, ${literal(template.stylesheet)}, ${literal(template.headerHtml)}, ${literal(template.footerHtml)}
${indent}WHERE NOT EXISTS (SELECT FROM hall.document_template WHERE kind = ${literal(template.kind)} AND document_type = ${literal(template.documentType)});`;
}

function migrationSql(defaults) {
  const inserts = insertedTypes.map((type) =>
    insertSql(
      defaults.find((entry) => entry.documentType === type),
      "",
    ),
  );
  return `-- Generated by scripts/distribution/document-template-sql.mjs; do not edit.
-- Document templates for HALL-FR-ATT-170 and HALL-FR-ATT-180: an installed database
-- receives the default attendance sheet and proxy form templates when it has none.
-- An existing template of these types is left unchanged; migration 007 gives
-- precedence to a template of the former server tables.
${inserts.join("\n")}
`;
}

function installationSql(defaults) {
  return `-- Generated by scripts/distribution/document-template-sql.mjs; do not edit.
-- @implements-requirement HALL-FR-CFG-020
-- A new installation receives the default template of every generated document; an installed
-- database keeps its templates, deleted ones included.
${defaults.map((template) => insertSql(template, "")).join("\n")}
`;
}

function replacementSql(defaults, previous) {
  const rows = replacedTypes.map((type) => {
    const current = defaults.find((entry) => entry.documentType === type && entry.kind === "pdf");
    const former = previous.find((entry) => entry.documentType === type && entry.kind === "pdf");
    return `    (${literal(type)}, ${literal(former?.bodyMarkdown ?? current.bodyMarkdown)}, ${literal(current.bodyMarkdown)}, ${literal(current.stylesheet)})`;
  });
  return `-- Generated by scripts/distribution/document-template-sql.mjs; do not edit.
-- Explicit replacement of the default PDF templates of hall.document_template, run after backup and hall migrate with psql.
-- A template whose body is still the default of ${previousRelease}, or already the current default,
-- receives the current default body and stylesheet and keeps its identifier and name. A customized
-- template is left unchanged and listed with outcome 'customized': add the signature block of the
-- current default to it by hand. The final query lists every template of these types and its outcome.
BEGIN;
CREATE TEMPORARY TABLE pg_temp.hall_default_template (
  document_type TEXT PRIMARY KEY,
  former_body TEXT NOT NULL,
  body TEXT NOT NULL,
  stylesheet TEXT NOT NULL
) ON COMMIT DROP;
INSERT INTO pg_temp.hall_default_template (document_type, former_body, body, stylesheet) VALUES
${rows.join(",\n")};
CREATE TEMPORARY TABLE pg_temp.hall_template_outcome ON COMMIT DROP AS
  SELECT t.id, t.document_type, t.name,
    CASE WHEN t.body_markdown = d.body AND t.stylesheet = d.stylesheet THEN 'current'
         WHEN t.body_markdown IN (d.former_body, d.body) THEN 'replaced'
         ELSE 'customized' END AS outcome
  FROM hall.document_template t JOIN pg_temp.hall_default_template d ON d.document_type = t.document_type
  WHERE t.kind = 'pdf';
UPDATE hall.document_template t SET body_markdown = d.body, stylesheet = d.stylesheet, updated_at = clock_timestamp()
  FROM pg_temp.hall_default_template d, pg_temp.hall_template_outcome o
  WHERE o.id = t.id AND d.document_type = t.document_type AND o.outcome = 'replaced';
SELECT document_type, name, id, outcome FROM pg_temp.hall_template_outcome ORDER BY document_type, name;
COMMIT;
`;
}

export async function documentTemplateSql() {
  const defaults = await currentDefaults();
  return {
    [migrationPath]: migrationSql(defaults),
    [replacementPath]: replacementSql(defaults, await previousDefaults()),
    [installationPath]: installationSql((await domainTemplates()).generatedDocumentTemplates),
  };
}

if (process.argv[1] && pathToFileURL(process.argv[1]).href === import.meta.url) {
  const check = process.argv.includes("--check");
  const files = await documentTemplateSql();
  let stale = false;
  for (const [path, content] of Object.entries(files)) {
    const existing = existsSync(path) ? readFileSync(path, "utf8") : null;
    if (existing === content) continue;
    if (check) {
      console.error(
        `${path} differs from the current default templates; run node scripts/distribution/document-template-sql.mjs`,
      );
      stale = true;
    } else {
      writeFileSync(path, content);
      console.log(`Written ${path}`);
    }
  }
  if (stale) process.exitCode = 1;
}
