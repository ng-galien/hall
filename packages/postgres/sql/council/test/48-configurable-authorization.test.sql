-- @verifies-requirement HALL-FR-USR-060
BEGIN;
SET LOCAL search_path=hall,public;
SET LOCAL hall.request_id='configurable-authorization';
SET LOCAL hall.actor_id='test-administrator';
SET LOCAL hall.action='role.update';
SET LOCAL hall.roles='["administrator"]';
SELECT no_plan();
SELECT is((hall_api.save_authorization_role('test-role', '{"name":"Test","revision":0,"grants":[{"access":"read","condition":"always"},{"access":"meeting.conduct","condition":"meetingOfficer"}]}')->>'revision')::int, 1, 'create persistent role');
SET LOCAL hall.roles='["test-role"]';
SELECT ok(hall.allows('application.read'), 'new role grants reading');
SELECT ok(NOT hall.allows('application.export'), 'ungranted export denied');
SELECT ok(NOT hall.allows('meeting.record-opening'), 'meetingOfficer requires a meeting and its officer');
SELECT throws_ok($$SELECT hall_api.authorization_configuration()$$, 'HV614', NULL, 'ordinary role cannot edit the policy');
SET LOCAL hall.roles='["administrator"]';
SELECT is((hall_api.save_authorization_role('test-role', '{"name":"Renamed","revision":1,"grants":[{"access":"meeting.conduct","condition":"always"}]}')->>'revision')::int, 2, 'update grants and condition');
SELECT throws_ok($$SELECT hall_api.save_authorization_role('test-role', '{"name":"Stale","revision":1,"grants":[]}')$$, 'HV803', NULL, 'stale editor cannot overwrite');
SELECT throws_ok($$SELECT hall_api.save_authorization_role('test-role', '{"name":"Invalid","revision":2,"grants":[{"access":"read","condition":"meetingOfficer"}]}')$$, 'HV802', NULL, 'invalid condition denied');
SELECT throws_ok($$SELECT hall_api.save_authorization_role('administrator', '{"name":"Changed","revision":1,"grants":[]}')$$, 'HV801', NULL, 'administrator rights cannot be withdrawn');
SELECT throws_ok($$SELECT hall_api.delete_authorization_role('administrator',1)$$, 'HV801', NULL, 'administrator role cannot be deleted');
SELECT hall.initialize_authorization_defaults();
SELECT is(hall.authorization_role_json('test-role')->>'name', 'Renamed', 'initialization preserves edits');
SET LOCAL hall.roles='["test-role"]';
SELECT ok(NOT hall.allows('application.read'), 'removed reading denied immediately');
SELECT ok(hall.allows('meeting.record-opening'), 'changed condition takes effect immediately');
SET LOCAL hall.roles='["test-role", "contributor"]';
SELECT ok(hall.allows('application.read'), 'role grants form a union');
SET LOCAL hall.roles='["administrator"]';
DELETE FROM hall.authorization_grant WHERE role='administrator';
SELECT ok(hall.allows('application.read') AND hall.allows('role.update') AND hall.allows('meeting.record-opening'), 'administrator is independent of mutable grants and context');
SELECT is((SELECT count(*)::int FROM hall.audit_event WHERE target_type='authorization-role' AND target_id='test-role'), 2, 'policy changes are audited');
SELECT * FROM finish();
ROLLBACK;
