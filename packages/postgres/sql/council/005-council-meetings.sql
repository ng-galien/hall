-- Entity: one council meeting. Its quorum is observed in conduct. A meeting may
-- be provisioned before its date is known. started_at and closed_at are facts,
-- not a mutable status: their nullability structurally expresses preparation,
-- conduct and closure.
CREATE TABLE council_meetings (
  id UUID PRIMARY KEY,

  -- @functional-requirement HALL-FR-MTG-190 COUNCIL_MEETING_NUMBER_IS_STABLE_SEQUENCE:
  -- Meeting numbers are positive, unique occurrences in the durable sequence.
  -- The first provisioned meeting is 1; closure gives its successor number + 1.
  number INTEGER GENERATED BY DEFAULT AS IDENTITY UNIQUE CHECK (number > 0),

  -- The predecessor relation forms the durable meeting sequence. The first
  -- known meeting has no predecessor; every later meeting has exactly one.
  previous_council_meeting UUID UNIQUE
    REFERENCES council_meetings (id),

  -- @functional-requirement HALL-FR-MTG-080 COUNCIL_MEETING_DATE_CAN_BE_UNSET:
  -- The next meeting exists before its date is necessarily fixed.
  scheduled_at TIMESTAMPTZ,

  -- @functional-requirement HALL-FR-MTG-200 COUNCIL_MEETING_SCHEDULE_IS_COMPLETE:
  -- A meeting is either still unprogrammed or has both a date and a non-blank
  -- location. These two facts are recorded atomically by the schedule action.
  location TEXT,

  -- @functional-requirement HALL-FR-MTG-230 COUNCIL_MEETING_OFFICERS_ARE_COUNCIL_MEMBERS:
  -- Officers may remain undesignated during preparation. They are durable
  -- CouncilMember identities once designated and must both exist before start.
  chair_member UUID REFERENCES hall.council_member (id) ON DELETE RESTRICT,
  secretary_member UUID REFERENCES hall.council_member (id) ON DELETE RESTRICT,

  started_at TIMESTAMPTZ,
  closed_at TIMESTAMPTZ,

  -- @functional-requirement HALL-FR-MTG-090 COUNCIL_MEETING_CLOSURE_REQUIRES_START:
  CONSTRAINT council_meeting_closure_requires_start CHECK (
    closed_at IS NULL OR started_at IS NOT NULL
  ),

  CONSTRAINT council_meeting_schedule_is_complete CHECK (
    (scheduled_at IS NULL AND location IS NULL)
    OR
    (scheduled_at IS NOT NULL AND location IS NOT NULL AND btrim(location) <> '')
  ),

  -- @functional-requirement HALL-FR-MTG-210 COUNCIL_MEETING_START_REQUIRES_SCHEDULE:
  CONSTRAINT council_meeting_start_requires_schedule CHECK (
    started_at IS NULL OR scheduled_at IS NOT NULL
  ),

  CONSTRAINT council_meeting_time_is_monotonic CHECK (
    closed_at IS NULL OR closed_at >= started_at
  ),

  CONSTRAINT council_meeting_is_not_its_own_predecessor CHECK (
    previous_council_meeting IS NULL OR previous_council_meeting <> id
  )
);
