import { minutesDetailSchema, minutesSummarySchema } from "@hall/api-contract";
import { expect, it } from "vitest";
import type { PostgresRequest } from "../src/callContext.js";
import { PostgresCouncil } from "../src/council.js";
import { PostgresDirectory } from "../src/directory.js";
import { PostgresMinutes } from "../src/minutes.js";
import { createTestPool, postgresDescribe, useFreshHallDatabase } from "./support/database.js";

postgresDescribe("standalone minutes", () => {
  const pool = createTestPool();
  const council = new PostgresCouncil(pool);
  const directory = new PostgresDirectory(pool);
  const minutes = new PostgresMinutes(pool);
  useFreshHallDatabase(pool);
  const request: PostgresRequest = {
    role: "hall_api_authenticated",
    context: { requestId: "minutes-test", actorId: "admin", councilMemberId: null, roles: ["administrator"] },
  };

  async function closeMeeting() {
    await directory.configureActiveCouncilTerm(request, 1);
    const contact = await directory.createContact(request, {
      firstName: "Camille",
      lastName: "Martin",
      organizationName: null,
      jobTitle: null,
      email: null,
      phone: null,
      notes: "",
    });
    const member = await directory.createCouncilMember(request, {
      contactId: contact.id,
      role: "mayor",
      termStartedOn: "2026-01-01",
    });
    const meeting = await council.provisionInitialMeeting(request, { quorum: 1 });
    await pool.query("SELECT hall.schedule_council_meeting($1,'2026-09-05 09:00Z','Chamber')", [meeting.id]);
    await pool.query("SELECT hall.set_council_meeting_officers($1,$2,$2)", [meeting.id, member.id]);
    await pool.query(
      "INSERT INTO hall.meeting_attendance(id,council_member,council_meeting,status) VALUES(gen_random_uuid(),$1,$2,'present')",
      [member.id, meeting.id],
    );
    const business = await council.createBusiness(request, {
      path: "seed",
      name: "Minutes fixture",
      reportName: "Report",
      reportContent: "",
    });
    await council.scheduleOpenQuestion(request, {
      councilBusinessId: business.id,
      councilMeetingId: meeting.id,
      position: 1,
    });
    await council.scheduleOpenQuestion(request, {
      councilBusinessId: business.id,
      councilMeetingId: meeting.id,
      position: 2,
    });
    await pool.query("SELECT hall.start_council_meeting($1,'2026-09-05 09:00Z')", [meeting.id]);
    return council.close(request, { id: meeting.id, closedAt: "2026-09-05T10:00:00Z" });
  }

  it("validates the HTTP projection contract and freezes the exact generated bytes", async () => {
    const closed = await closeMeeting();
    expect(minutesSummarySchema.parse(closed.minutes)).toEqual(closed.minutes);
    const draft = await minutes.open(request, closed.minutes.id);
    expect(minutesDetailSchema.parse(draft)).toEqual(draft);
    expect(draft?.facts.meeting.chair?.name).toBe("Camille Martin");
    expect(await minutes.list(request)).toEqual([closed.minutes]);
    const updated = await minutes.updateDraft(request, {
      id: closed.minutes.id,
      expectedVersion: 1,
      agendaItemId: draft!.sections[0]!.agendaItemId,
      content: "Corrected text.",
    });
    expect(updated.version).toBe(2);
    expect(updated.sections).toHaveLength(2);
    expect(updated.sections[0]?.content).toBe("Corrected text.");
    expect(updated.sections[1]?.content).toBe("");
    expect(updated.facts).toEqual(draft?.facts);
    const content = Buffer.from("%PDF-1.4 test generated bytes");
    const generated = await minutes.generate(request, { id: updated.id, expectedVersion: 2, content });
    expect(minutesDetailSchema.parse(generated)).toEqual(generated);
    expect(generated.documentId).toBeTruthy();
    expect((await minutes.content(request, generated.id))?.content).toEqual(content);
    await expect(
      minutes.updateDraft(request, {
        id: generated.id,
        expectedVersion: 2,
        agendaItemId: draft!.sections[0]!.agendaItemId,
        content: "Late",
      }),
    ).rejects.toMatchObject({ code: "HV704" });
    expect((await pool.query("SELECT count(*)::integer count FROM hall.council_business")).rows[0].count).toBe(1);
    expect((await council.listAgenda(request, closed.nextMeeting.id))[0]).toMatchObject({
      councilBusinessId: null,
      subject: { kind: "minutesApproval", minutesId: generated.id, documentId: generated.documentId },
    });
  });

  it("serializes generation against draft edits and duplicate generation", async () => {
    const closed = await closeMeeting();
    const first = await pool.connect();
    const second = await pool.connect();
    const pdf = Buffer.from("%PDF-1.4 concurrency test");
    try {
      await first.query("BEGIN");
      await first.query(
        "SELECT hall_api.update_minutes_draft($1,1,(SELECT agenda_item FROM hall.minutes_section WHERE minutes=$1 LIMIT 1),'New section')",
        [closed.minutes.id],
      );
      const firstPid = (await first.query("SELECT pg_backend_pid() pid")).rows[0].pid;
      const secondPid = (await second.query("SELECT pg_backend_pid() pid")).rows[0].pid;
      const pending = second.query("SELECT hall_api.generate_minutes($1,1,$2)", [closed.minutes.id, pdf]).then(
        () => null,
        (error: unknown) => error,
      );
      const deadline = Date.now() + 3000;
      let blocked = false;
      while (Date.now() < deadline) {
        blocked = (await pool.query("SELECT $1::int = ANY(pg_blocking_pids($2::int)) blocked", [firstPid, secondPid]))
          .rows[0].blocked;
        if (blocked) break;
        await new Promise((resolve) => setTimeout(resolve, 10));
      }
      expect(blocked).toBe(true);
      await first.query("COMMIT");
      expect(await pending).toMatchObject({ code: "HV708" });
      expect((await minutes.open(request, closed.minutes.id))?.documentId).toBeNull();

      await first.query("BEGIN");
      await first.query("SELECT hall_api.generate_minutes($1,2,$2)", [closed.minutes.id, pdf]);
      const duplicate = second.query("SELECT hall_api.generate_minutes($1,2,$2)", [closed.minutes.id, pdf]).then(
        () => null,
        (error: unknown) => error,
      );
      await first.query("COMMIT");
      expect(await duplicate).toMatchObject({ code: "HV704" });
      expect((await pool.query("SELECT count(*)::integer count FROM hall.minutes_document")).rows[0].count).toBe(1);
    } finally {
      await first.query("ROLLBACK");
      first.release();
      second.release();
    }
  });
});
