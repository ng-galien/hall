import { appendFile, mkdir, readdir, rm } from "node:fs/promises";
import { dirname, join } from "node:path";

// @implements-requirement HALL-TR-DST-020
export const backupArchivePattern = /^hall-.+\.dump$/;

/** Archive names of a backup folder, oldest first (names carry a sortable UTC time). */
export async function archivesIn(directory) {
  return (await readdir(directory)).filter((name) => backupArchivePattern.test(name)).sort();
}

/** Removes the oldest archives and their manifests so that `retention` archives remain. */
export async function pruneArchives(directory, retention) {
  const archives = await archivesIn(directory);
  const removed = archives.slice(0, Math.max(0, archives.length - retention));
  for (const name of removed) {
    await rm(join(directory, name), { force: true });
    await rm(join(directory, `${name}.json`), { force: true });
  }
  return removed;
}

/** Appends one JSON line to an owner-only operation log. */
export async function appendJsonLine(file, record) {
  await mkdir(dirname(file), { recursive: true, mode: 0o700 });
  await appendFile(file, `${JSON.stringify({ time: new Date().toISOString(), ...record })}\n`, { mode: 0o600 });
}

function powershellString(value) {
  return `'${String(value).replaceAll("'", "''")}'`;
}

function commandLineArgument(value) {
  return `"${String(value).replaceAll('"', '\\"')}"`;
}

/**
 * The PowerShell script that takes and verifies a first backup, then registers
 * the daily backup and weekly verification tasks under the current account. S4U logon runs the
 * tasks while nobody is signed in, without storing a password; both tasks write their outcome
 * to logs\backup.log themselves.
 */
export function windowsTasksScript({ node, cli, environmentFile, backupTime = "02:00", verifyTime = "03:00" }) {
  const argumentsOf = (command) =>
    powershellString(`${commandLineArgument(cli)} ${command} --env-file ${commandLineArgument(environmentFile)}`);
  return `# Hall: daily backup and weekly backup verification (generated by hall windows-tasks)
$ErrorActionPreference = 'Stop'
$Node = ${powershellString(node)}
$Cli = ${powershellString(cli)}
$Config = ${powershellString(environmentFile)}
& $Node $Cli backup --env-file $Config
if ($LASTEXITCODE -ne 0) { throw 'First backup failed: check DATABASE_URL and the PostgreSQL client tools; no task registered' }
& $Node $Cli verify-backup --env-file $Config
if ($LASTEXITCODE -ne 0) { throw 'First backup verification failed: no task registered' }
$Principal = New-ScheduledTaskPrincipal -UserId "$env:USERDOMAIN\\$env:USERNAME" -LogonType S4U -RunLevel Limited
$Settings = New-ScheduledTaskSettingsSet -StartWhenAvailable -MultipleInstances IgnoreNew -ExecutionTimeLimit (New-TimeSpan -Hours 2)
$WorkingDirectory = Split-Path -Parent $Config
$Backup = New-ScheduledTaskAction -Execute $Node -Argument ${argumentsOf("backup")} -WorkingDirectory $WorkingDirectory
$Verify = New-ScheduledTaskAction -Execute $Node -Argument ${argumentsOf("verify-backup")} -WorkingDirectory $WorkingDirectory
Register-ScheduledTask -Force -TaskName 'Hall - sauvegarde' -Action $Backup -Trigger (New-ScheduledTaskTrigger -Daily -At ${powershellString(backupTime)}) -Principal $Principal -Settings $Settings | Out-Null
Register-ScheduledTask -Force -TaskName 'Hall - verification de sauvegarde' -Action $Verify -Trigger (New-ScheduledTaskTrigger -Weekly -DaysOfWeek Sunday -At ${powershellString(verifyTime)}) -Principal $Principal -Settings $Settings | Out-Null
Get-ScheduledTask -TaskName 'Hall - sauvegarde', 'Hall - verification de sauvegarde' | Format-Table TaskName, State
Write-Output 'Tasks registered. The outcome of each run is appended to the logs\\backup.log file beside the environment file.'
`;
}
